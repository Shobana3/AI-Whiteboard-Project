const DrawingCanvas = forwardRef(({ onDrawingChange }, ref) => {
  const canvasRef      = useRef(null);
  const lastPos        = useRef(null);
  const catScrollRef   = useRef(null);   // wheel-scroll for category row
  const shapesScrollRef = useRef(null);  // wheel-scroll for shapes row
  const [isDrawing,    setIsDrawing]    = useState(false);
  const [tool,         setTool]         = useState('pen');
  const [color,        setColor]        = useState('#1A1714');
  const [brushSize,    setBrushSize]    = useState(4);
  const [history,      setHistory]      = useState([]);
  const [historyIndex, setHistoryIndex] = useState(-1);
  const [traceShape,   setTraceShape]   = useState(null);
  const [openCategory, setOpenCategory] = useState(null);

  const hasDrawingRef = useRef(false); // tracks if user has actually drawn anything

  useImperativeHandle(ref, () => ({
    getCanvasData:  () => canvasRef.current?.toDataURL('image/png'),
    clearCanvas:    () => clearCanvas(),
    getCanvas:      () => canvasRef.current,
    getTraceShape:  () => traceShape ? TRACE_SHAPES.find(s => s.id === traceShape)?.label || null : null,
    isCanvasBlank:  () => !hasDrawingRef.current,
  }));

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    const data = canvas.toDataURL();
    setHistory([data]);
    setHistoryIndex(0);
  }, []);

  const saveToHistory = useCallback(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const data = canvas.toDataURL();
    setHistory(prev => {
      const h = prev.slice(0, historyIndex + 1);
      h.push(data);
      return h.slice(-30);
    });
    setHistoryIndex(prev => Math.min(prev + 1, 29));
  }, [historyIndex]);

  const getPos = (e, canvas) => {
    const rect = canvas.getBoundingClientRect();
    const sx = canvas.width / rect.width;
    const sy = canvas.height / rect.height;
    const src = e.touches ? e.touches[0] : e;
    return { x: (src.clientX - rect.left) * sx, y: (src.clientY - rect.top) * sy };
  };

  const startDrawing = (e) => {
    e.preventDefault();
    const canvas = canvasRef.current;
    const pos = getPos(e, canvas);
    setIsDrawing(true);
    lastPos.current = pos;
    const ctx = canvas.getContext('2d');
    if (tool === 'fill') {
      floodFill(ctx, Math.round(pos.x), Math.round(pos.y), color);
      hasDrawingRef.current = true;  // ← fill also counts as drawing
      saveToHistory();
      onDrawingChange?.();
    }
  };

  const draw = (e) => {
    e.preventDefault();
    if (!isDrawing || tool === 'fill') return;
    const canvas = canvasRef.current;
    const ctx = canvas.getContext('2d');
    const pos = getPos(e, canvas);
    ctx.lineJoin = 'round';
    ctx.lineCap  = 'round';
    if (tool === 'eraser') {
      // Paint white — matches the canvas background, no transparent checkerboard
      ctx.globalCompositeOperation = 'source-over';
      ctx.strokeStyle = '#FFFFFF';
      ctx.lineWidth   = brushSize * 3;
    } else {
      ctx.globalCompositeOperation = 'source-over';
      ctx.strokeStyle = color;
      ctx.lineWidth   = brushSize;
    }
    ctx.beginPath();
    ctx.moveTo(lastPos.current.x, lastPos.current.y);
    ctx.lineTo(pos.x, pos.y);
    ctx.stroke();
    lastPos.current = pos;
    hasDrawingRef.current = true;  // ← mark canvas as no longer blank
    onDrawingChange?.();
  };

  const stopDrawing = () => {
    if (isDrawing) { setIsDrawing(false); saveToHistory(); }
  };

  const clearCanvas = () => {
    const canvas = canvasRef.current;
    const ctx = canvas.getContext('2d');
    ctx.globalCompositeOperation = 'source-over';
    ctx.fillStyle = '#FFFFFF';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    hasDrawingRef.current = false;  // ← reset blank state
    saveToHistory();
    onDrawingChange?.();
  };

  const undo = () => {
    if (historyIndex <= 0) return;
    const newIndex = historyIndex - 1;
    setHistoryIndex(newIndex);
    if (newIndex === 0) hasDrawingRef.current = false; // ← back to blank
    const canvas = canvasRef.current;
    const ctx = canvas.getContext('2d');
    const img = new Image();
    img.onload = () => {
      ctx.globalCompositeOperation = 'source-over';
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ctx.drawImage(img, 0, 0);
    };
    img.src = history[newIndex];
    onDrawingChange?.();
  };

  const floodFill = (ctx, x, y, fillColorHex) => {
    const canvas = canvasRef.current;
    const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
    const data = imageData.data;
    const ti = (y * canvas.width + x) * 4;
    const tc = [data[ti], data[ti+1], data[ti+2], data[ti+3]];
    const h2r = hex => {
      // Handle 3-digit hex like #F00
      const h = hex.length === 4
        ? '#' + hex[1]+hex[1]+hex[2]+hex[2]+hex[3]+hex[3]
        : hex;
      return [parseInt(h.slice(1,3),16), parseInt(h.slice(3,5),16), parseInt(h.slice(5,7),16), 255];
    };
    const fc = h2r(fillColorHex);
    if (JSON.stringify(tc) === JSON.stringify(fc)) return;
    const match = i => data[i]===tc[0] && data[i+1]===tc[1] && data[i+2]===tc[2] && Math.abs(data[i+3]-tc[3])<30;
    const set   = i => { data[i]=fc[0]; data[i+1]=fc[1]; data[i+2]=fc[2]; data[i+3]=fc[3]; };
    const stack = [[x, y]];
    const vis = new Set();
    while (stack.length) {
      const [cx, cy] = stack.pop();
      if (cx<0 || cy<0 || cx>=canvas.width || cy>=canvas.height) continue;
      const k = `${cx},${cy}`;
      if (vis.has(k)) continue;
      vis.add(k);
      const idx = (cy * canvas.width + cx) * 4;
      if (!match(idx)) continue;
      set(idx);
      stack.push([cx+1,cy],[cx-1,cy],[cx,cy+1],[cx,cy-1]);
    }
    ctx.putImageData(imageData, 0, 0);
  };

  const handleSelectTrace = (shapeId) => {
    setTraceShape(prev => prev === shapeId ? null : shapeId);
  };

  const handleCategoryClick = (catId) => {
    setOpenCategory(prev => prev === catId ? null : catId);
  };

  const activeShapeData = traceShape ? TRACE_SHAPES.find(s => s.id === traceShape) : null;
  const openCatData = openCategory ? TRACE_CATEGORIES.find(c => c.id === openCategory) : null;

  const tools = [
    { id: 'pen',    icon: '✏️', label: 'Pen' },
    { id: 'eraser', icon: '🧽', label: 'Eraser' },
    { id: 'fill',   icon: '🪣', label: 'Fill' },
  ];

  return (
    <div className="canvas-wrapper">
      {/* ── Main toolbar ── */}
      <div className="toolbar">
        <div className="toolbar-section">
          {tools.map(t => (
            <button key={t.id}
              className={`tool-btn ${tool === t.id ? 'active' : ''}`}
              onClick={() => setTool(t.id)} title={t.label}>{t.icon}</button>
          ))}
        </div>
        <div className="toolbar-sep" />
        <div className="toolbar-section color-row">
          {COLORS.map(c => (
            <button key={c}
              className={`color-swatch ${color === c ? 'active' : ''}`}
              style={{ background: c, border: c === '#FFFFFF' ? '1.5px solid #E8E4DC' : 'none' }}
              onClick={() => { setColor(c); setTool('pen'); }} title={c} />
          ))}
          <label className="color-picker-wrap" title="Custom color">
            <span className="color-picker-icon">🌈</span>
            <input type="color" value={color}
              onChange={e => { setColor(e.target.value); setTool('pen'); }} />
          </label>
        </div>
        <div className="toolbar-sep" />
        <div className="toolbar-section brush-section">
          <span className="brush-label">SIZE</span>
          <input type="range" min="1" max="30" value={brushSize}
            onChange={e => setBrushSize(Number(e.target.value))} className="brush-slider" />
          <div className="brush-dot" style={{
            width:      Math.max(6, brushSize),
            height:     Math.max(6, brushSize),
            background: tool === 'eraser' ? '#D0CBC2' : color,
            border:     color === '#FFFFFF' ? '1.5px solid #E8E4DC' : 'none',
          }} />
        </div>
        <div className="toolbar-sep" />
        <div className="toolbar-section">
          <button className="tool-btn" onClick={undo}
            disabled={historyIndex <= 0} title="Undo">↩️</button>
        </div>
      </div>

      {/* ── Two-level trace bar ── */}
      <div className="trace-bar">
        {/* Level 1: Category pills */}
        <div className="trace-cat-row">
          <span className="trace-label">✏️ Trace:</span>
          <div
            className="trace-scroll"
            ref={catScrollRef}
            onWheel={e => { e.preventDefault(); catScrollRef.current.scrollLeft += e.deltaY * 1.5; }}
          >
            {TRACE_CATEGORIES.map(cat => (
              <button
                key={cat.id}
                className={`trace-cat-btn${openCategory === cat.id ? ' active' : ''}${cat.shapes.some(s => s.id === traceShape) ? ' has-active' : ''}`}
                onClick={() => handleCategoryClick(cat.id)}
              >
                {cat.emoji} {cat.label}
                <span className="trace-cat-arrow">{openCategory === cat.id ? ' ▲' : ' ▼'}</span>
              </button>
            ))}
          </div>
          {traceShape && (
            <button className="trace-close" onClick={() => setTraceShape(null)} title="Remove guide">✕</button>
          )}
        </div>

        {/* Level 2: Shape chips for open category */}
        {openCatData && (
          <div className="trace-shapes-row">
            <div
              className="trace-scroll"
              ref={shapesScrollRef}
              onWheel={e => { e.preventDefault(); shapesScrollRef.current.scrollLeft += e.deltaY * 1.5; }}
            >
              {openCatData.shapes.map(s => (
                <button
                  key={s.id}
                  className={`trace-chip${traceShape === s.id ? ' active' : ''}`}
                  onClick={() => handleSelectTrace(s.id)}
                >
                  {s.emoji} {s.label}
                </button>
              ))}
            </div>
          </div>
        )}
      </div>

      {/* ── Canvas area with SVG overlay ── */}
      <div className="canvas-area">
        <canvas
          ref={canvasRef}
          width={900}
          height={520}
          className={`draw-canvas cursor-${tool}`}
          onMouseDown={startDrawing}
          onMouseMove={draw}
          onMouseUp={stopDrawing}
          onMouseLeave={stopDrawing}
          onTouchStart={startDrawing}
          onTouchMove={draw}
          onTouchEnd={stopDrawing}
        />

        {activeShapeData && (
          <svg
            className="trace-overlay"
            viewBox="0 0 900 520"
            xmlns="http://www.w3.org/2000/svg"
            preserveAspectRatio="xMidYMid meet"
          >
            {activeShapeData.paths.slice(0,1).map((d, i) => (
              <path key={`fill-${i}`} d={d} fill="rgba(91,79,232,0.07)" stroke="none" />
            ))}
            {activeShapeData.paths.map((d, i) => (
              <path
                key={`path-${i}`}
                d={d}
                fill="none"
                stroke="rgba(91,79,232,0.55)"
                strokeWidth="3"
                strokeDasharray="10 7"
                strokeLinecap="round"
                strokeLinejoin="round"
              />
            ))}
            <text x="450" y="35" textAnchor="middle"
              fill="rgba(91,79,232,0.7)" fontSize="16" fontWeight="700" fontFamily="Nunito, sans-serif">
              Trace the {activeShapeData.label.toLowerCase()}!
            </text>
          </svg>
        )}
      </div>
    </div>
  );
});

export default DrawingCanvas;